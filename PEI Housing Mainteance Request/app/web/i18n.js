  /* Words in a description that bring back the call screen. Both languages are always checked. */
  const EMERGENCY_WORDS = ['gas leak', 'smell gas', 'gas', 'smoke', 'fire', 'flood', 'flooding', 'sparks', 'sparking', 'no water', 'burning', 'huele a gas', 'humo', 'fuego', 'inundación', 'inundacion', 'inundado', 'chispas', 'sin agua', 'quemando'];

  function matchWords(text) {
    const t = ' ' + String(text).toLowerCase().replace(/[^\p{L}\s]/gu, ' ').replace(/\s+/g, ' ') + ' ';
    const hits = EMERGENCY_WORDS.filter((w) => t.includes(' ' + w + ' '));
    // "gas" is dropped when "smell gas" also matched, so the worker sees the phrase they wrote.
    return hits.filter((w) => !hits.some((o) => o !== w && o.includes(w)));
  }

